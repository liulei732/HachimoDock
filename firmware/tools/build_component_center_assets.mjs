// Encode factory launcher cards from the same covers the desktop catalog displays.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { deflateSync, inflateSync } from 'node:zlib';

const tools = dirname(fileURLToPath(import.meta.url));
const firmware = resolve(tools, '..');
const out = join(firmware, 'assets/component-center');
const { components } = JSON.parse(readFileSync(join(firmware, 'factory-config.json')));
const python = process.env.CENTER_THUMB_PYTHON || 'python3';
const frames = [];
const records = [];
let offset = 0;

for (const id of components.ids) {
  const directory = components.firmwareOnlyIds?.includes(id)
    ? components.firmwareOnlyPackagesDir : components.packagesDir;
  const pkg = resolve(firmware, directory, id);
  const widget = JSON.parse(readFileSync(join(pkg, 'runtime/widget.json')));
  const manifest = JSON.parse(readFileSync(join(pkg, 'component.json')));
  if (manifest.id !== id) throw Error(`Catalog ID differs from package ID: ${id}`);
  const source = readFileSync(join(pkg, 'pc/cover.png'));
  const raw = execFileSync(python, [join(tools, 'pack_center_thumbnail.py'), '--cover'], { input: source });
  if (raw.length !== 1568) throw Error(`Invalid 64×48 thumbnail for ${id}`);
  const frame = process.argv.includes('--zopfli')
    ? execFileSync(python, ['-c', 'import sys; from zopfli.zlib import compress; sys.stdout.buffer.write(compress(sys.stdin.buffer.read(), numiterations=15))'], { input: raw })
    : deflateSync(raw, { level: 9 });
  if (!inflateSync(frame).equals(raw)) throw Error(`Thumbnail round trip failed: ${id}`);
  const caption = widget.host || widget.data || widget.media
    ? '连接电脑使用' : manifest.kind === 'game' ? '开始一场小游戏' : '随时打开体验';
  const sha = createHash('sha256').update(source).digest('hex');
  records.push(`  {${JSON.stringify(id)}, ${JSON.stringify(caption)}, true, ${offset}, ${frame.length}}, /* ${sha} */`);
  frames.push(frame);
  offset += frame.length;
}

const header = `/* Generated by build_component_center_assets.mjs. Each stream is one PC cover. */\n#include <stdbool.h>\n#include <stdint.h>\nstatic const struct { const char *id, *caption; bool art; uint32_t offset; uint16_t length; } center_art_catalog[] = {\n${records.join('\n')}\n};\n#define CENTER_ART_COUNT (sizeof(center_art_catalog)/sizeof(center_art_catalog[0]))\n`;
const packed = Buffer.concat(frames);
const background = join(out, 'center_background.jpg');
// The background and cards have independent inputs. Re-encode the background only
// when replacing its artwork; a cover update need not carry a different JPEG codec build.
if (process.argv.includes('--background')) {
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', join(out, 'background.png'),
    '-frames:v', '1', '-q:v', '7', '-pix_fmt', 'yuvj420p', background]);
}
const totalBytes = packed.length + readFileSync(background).length;
if (totalBytes > 128 * 1024) throw Error('Launcher artwork exceeds 128 KiB');
writeFileSync(join(out, 'center_thumbs.deflate'), packed);
writeFileSync(join(out, 'catalog.h'), header);
console.log(`${frames.length} factory covers, ${packed.length} compressed bytes, ${totalBytes} bytes including background`);
